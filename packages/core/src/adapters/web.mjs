/**
 * The web adapter: plain ICU JSON, one file per locale, plus a TypeScript
 * declaration that types each key's arguments.
 *
 * This is the reference adapter. It can express everything the catalog can, so
 * it is where the export pipeline gets proven before the lossy native formats
 * are built on top of it.
 *
 * The generated `.d.ts` is the part that earns its keep. A key-only union
 * catches a typo in a key name, which is the easy half. Typing the ARGUMENTS
 * catches the case that actually ships broken: someone renames a placeholder in
 * the catalog, every call site still passes the old one, and the string renders
 * with a hole in it. That becomes a compile error here.
 *
 * A missing translation is omitted from the locale file rather than filled with
 * source text. The runtime then walks the fallback chain and can report the gap.
 * Writing English into de.json would make the file look complete while shipping
 * English, which is the failure this whole design refuses.
 */

import { join } from 'node:path'
import { serializeJson, GENERATED_KEY, GENERATED_NOTICE, jsonIsOurs } from '../writer.mjs'
import { messagesForTarget } from './index.mjs'

/** ICU argument kinds to the TypeScript type a caller must supply. */
const TS_TYPE = {
  plural: 'number',
  selectordinal: 'number',
  number: 'number',
  date: 'Date | number',
  time: 'Date | number',
  select: 'string',
  string: 'string | number',
}

function argType(kinds) {
  // An argument used two ways at once, say as both a plural selector and a
  // bare value, must satisfy both. Numbers are the narrower of the pair.
  if (kinds.has('plural') || kinds.has('selectordinal') || kinds.has('number')) return 'number'
  if (kinds.has('date') || kinds.has('time')) return 'Date | number'
  if (kinds.has('select')) return 'string'
  return TS_TYPE.string
}

function declarationFor(analysis) {
  const parts = []
  for (const [name, meta] of analysis.args) {
    parts.push(`${JSON.stringify(name)}: ${argType(meta.kinds)}`)
  }
  for (const tag of analysis.tags) {
    // A tag is a rendering hook, not a value: the caller decides what <link>
    // becomes in their framework.
    parts.push(`${JSON.stringify(tag)}: (children: string) => unknown`)
  }
  if (parts.length === 0) return 'Record<string, never>'
  return `{ ${parts.join('; ')} }`
}

export default {
  id: 'web',

  capabilities: {
    plurals: 'icu',
    exactMatch: true,
    select: true,
    selectordinal: true,
    offset: true,
    nesting: 3,
    placeholders: 'named',
    repeatedPlaceholders: true,
    numberArgs: true,
    dateTimeArgs: true,
    numberDateSkeletons: true,
    richText: true,
    comments: 'none',
    needsLocaleMap: false,
  },

  /** BCP 47 as-is. The web is the one platform that agrees with the standard. */
  localeTag(locale) {
    return locale
  },

  isOurs: jsonIsOurs,

  /**
   * @param {{project: import('../catalog.mjs').Project, config: object, target: object}} ctx
   * @returns {Array<{path: string, contents: string, generated: boolean, isOurs?: (c: string) => boolean}>}
   */
  emit({ project, config, target }) {
    const outDir = target.out ?? join(config.paths.out, target.name)
    const messages = messagesForTarget(project, target.name)
    const files = []

    const locales = [config.sourceLocale, ...config.targetLocales()]

    for (const locale of locales) {
      const isSource = locale === config.sourceLocale
      const body = {}

      for (const { namespace, key, entry } of messages) {
        if (isSource) {
          body[key] = entry.message
          continue
        }
        const translation = project.translationEntry(locale, namespace, key)
        // Omit rather than substitute. See the module comment.
        if (typeof translation?.message === 'string') body[key] = translation.message
      }

      files.push({
        path: join(outDir, 'locales', `${locale}.json`),
        contents: serializeJson({
          [GENERATED_KEY]: GENERATED_NOTICE,
          locale,
          messages: body,
        }),
        generated: true,
        isOurs: jsonIsOurs,
      })
    }

    files.push({
      path: join(outDir, 'keys.d.ts'),
      contents: typeDeclaration(project, messages),
      generated: true,
      isOurs: (contents) => contents.startsWith('// Generated by i18n-kit'),
    })

    return files
  },
}

function typeDeclaration(project, messages) {
  const lines = [
    '// Generated by i18n-kit. Do not edit: your changes will be overwritten on the',
    '// next export. Edit the catalog under i18n/ instead.',
    '',
    '/**',
    ' * Every message key, mapped to the arguments its ICU text requires.',
    ' *',
    ' * Renaming a placeholder in the catalog turns every stale call site into a',
    ' * compile error, which is the point: the alternative is a string that renders',
    ' * with a hole in it and nobody notices until a user does.',
    ' */',
    'export interface I18nMessages {',
  ]

  for (const { key, entry } of messages) {
    const analysis = project.tryAnalysisOf(entry.message)
    if (!analysis) continue // the parse error is reported by check, not here
    if (entry.comment) lines.push(`  /** ${entry.comment.replace(/\*\//g, '*\\/')} */`)
    lines.push(`  ${JSON.stringify(key)}: ${declarationFor(analysis)}`)
  }

  lines.push(
    '}',
    '',
    'export type I18nKey = keyof I18nMessages',
    'export type I18nArgs<K extends I18nKey> = I18nMessages[K]',
    '',
  )

  return lines.join('\n')
}
