/**
 * The Android adapter: `res/values-<tag>/strings.xml`.
 *
 * Android's plural is not ICU's. `getQuantityString` returns one whole string
 * per CLDR category, so a message like "Send {count, plural, ...} to {device}?"
 * becomes a `<plurals>` whose every `<item>` repeats the surrounding sentence.
 * That is the `explode` strategy: the structure is flattened at export rather
 * than at authoring time, so the catalog keeps one message and the platform
 * gets the shape it needs.
 *
 * Which categories to write is decided per locale from CLDR, not from the
 * source. English has two and Russian has four, so a Russian file that copies
 * English's two branches is wrong in the way users notice: "5 вкладки" instead
 * of "5 вкладок".
 *
 * Only one plural per message is expressible, because a quantity string has
 * exactly one quantity. Two plurals in one sentence is reported by the
 * capability check instead of being exported half-right.
 */

import { join } from 'node:path'
import { categoriesFor } from '../plurals.mjs'
import { messagesForTarget } from './index.mjs'
import { renderMessage, argPositions, chooseBranch, RenderError } from './render.mjs'

const GENERATED_MARKER = 'Generated by i18n-kit'

/** CLDR order, so files read the same way whatever locale they hold. */
const CATEGORY_ORDER = ['zero', 'one', 'two', 'few', 'many', 'other']

/**
 * Escape for an Android string resource.
 *
 * Both layers at once: XML entities so the file parses, and Android's own
 * backslash escapes so the resource compiler does not eat characters. `'` is
 * the one that bites, because the compiler treats an unescaped apostrophe as an
 * error in some positions and silently drops it in others.
 */
function escapeAndroid(text) {
  return text
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll("'", "\\'")
    .replaceAll('"', '\\"')
    .replaceAll('\n', '\\n')
    .replaceAll('\t', '\\t')
    // A literal percent sign has to be doubled or String.format reads it as a
    // conversion and throws at runtime.
    .replace(/%(?![0-9]+\$|[sdfe%])/g, '%%')
}

/**
 * Significant leading or trailing space survives only inside literal quotes.
 *
 * Decided on the LITERAL text, with placeholders standing in as a non-space
 * character. A string that merely ends with an argument — "Now using %1$s" —
 * has no trailing space and must not be quoted: Android would keep the quotes
 * as part of the string.
 */
const PLACEHOLDER_STANDIN = '\u0001'

function wrapIfPadded(escaped, literalShape) {
  return literalShape !== literalShape.trim() ? `"${escaped}"` : escaped
}

const CONVERSION = { number: 'd', string: 's', date: 's', time: 's' }

/**
 * One Android format string for a single plural category.
 *
 * @param {string} text            the message to render
 * @param {object} project
 * @param {{positions: Map<string,number>, category: string|null, pluralArg: string|null}} ctx
 */
function toAndroid(text, project, { positions, category, pluralArg }) {
  const analysis = project.analysisOf(text)
  let raw = ''

  const out = renderMessage(analysis.ast, {
    literal: (value) => {
      raw += value
      return escapeAndroid(value)
    },
    arg: (name, kind) => {
      const index = positions.get(name)
      if (index === undefined) {
        // An argument the source does not have. `check` reports this as a
        // placeholder mismatch; refusing here keeps a wrong file off disk.
        throw new RenderError(`{${name}} is not an argument of the source message, so it has no position`)
      }
      raw += PLACEHOLDER_STANDIN
      return `%${index}$${CONVERSION[kind] ?? 's'}`
    },
    pound: () => {
      const index = positions.get(pluralArg)
      raw += PLACEHOLDER_STANDIN
      return `%${index}$d`
    },
    plural: (node, render) => {
      if (node.value !== pluralArg) {
        throw new RenderError(`a second plural on {${node.value}} cannot be expressed: a quantity string has one quantity`)
      }
      return chooseBranch(node, category, render)
    },
  })

  return wrapIfPadded(out, raw)
}

export default {
  id: 'android',

  capabilities: {
    plurals: 'explode',
    exactMatch: false,
    select: false,
    selectordinal: false,
    offset: false,
    nesting: 2,
    placeholders: 'positional',
    repeatedPlaceholders: true,
    numberArgs: true,
    dateTimeArgs: false,
    numberDateSkeletons: false,
    richText: false,
    comments: 'default-locale-only',
    needsLocaleMap: false,
  },

  /**
   * Android's resource qualifier.
   *
   * Legacy mode predates BCP 47 entirely: `de`, `pt-rBR`, and no way to say
   * `zh-Hans` at all. Config rejects that pairing rather than truncating here.
   */
  localeTag(locale, target) {
    if (target?.options?.localeFormat === 'bcp47') return `b+${locale.replaceAll('-', '+')}`
    const [language, ...rest] = locale.split('-')
    const region = rest.find((part) => /^[A-Z]{2}$/.test(part) || /^\d{3}$/.test(part))
    return region ? `${language}-r${region}` : language
  },

  isOurs: (contents) => contents.includes(GENERATED_MARKER),

  emit({ project, config, target }) {
    const resDir = target.out ?? join(config.paths.out, target.name, 'res')
    const messages = messagesForTarget(project, target.name)
    const files = []

    const locales = config.source?.mode === 'adopt' ? [config.sourceLocale, ...config.targetLocales()] : config.targetLocales()

    for (const locale of locales) {
      const isSource = locale === config.sourceLocale
      const qualifier = isSource ? 'values' : `values-${this.localeTag(locale, target)}`
      const categories = categoriesFor(locale)
      const body = []

      for (const { namespace, key, entry } of messages) {
        const text = isSource ? entry.message : project.translationEntry(locale, namespace, key)?.message
        // Omitted, never filled with English. Android then falls back to
        // values/ on its own, which is the behaviour a user expects, and the
        // gap stays visible in `check` instead of being papered over.
        if (typeof text !== 'string') continue

        const name = entry.platformNames?.android ?? key.replaceAll('.', '_')
        const sourceAnalysis = project.tryAnalysisOf(entry.message)
        if (!sourceAnalysis) continue
        const positions = argPositions(sourceAnalysis)

        const analysis = project.tryAnalysisOf(text)
        if (!analysis) continue
        const plural = analysis.plurals[0] ?? null

        // A comment is worth writing only in the default locale: the
        // translations are generated, and a translator never reads them.
        if (isSource && entry.comment) {
          body.push(`    <!-- ${entry.comment.replaceAll('--', '—')} -->`)
        }

        if (!plural) {
          body.push(`    <string name="${name}">${toAndroid(text, project, { positions, category: null, pluralArg: null })}</string>`)
          continue
        }

        if (argPositions(sourceAnalysis).get(plural.arg) !== 1) {
          throw new RenderError(
            `the plural argument {${plural.arg}} is argument ` +
              `${argPositions(sourceAnalysis).get(plural.arg)} of this message, and Android's ` +
              `getQuantityString passes the quantity first. Put it first in the source message, ` +
              `or the generated %N$d will not be the count.`,
          )
        }

        const items = categories
          .slice()
          .sort((a, b) => CATEGORY_ORDER.indexOf(a) - CATEGORY_ORDER.indexOf(b))
          .map((category) => {
            const rendered = toAndroid(text, project, { positions, category, pluralArg: plural.arg })
            return `        <item quantity="${category}">${rendered}</item>`
          })

        body.push(`    <plurals name="${name}">`, ...items, '    </plurals>')
      }

      files.push({
        path: join(resDir, qualifier, 'strings.xml'),
        contents: [
          '<?xml version="1.0" encoding="utf-8"?>',
          `<!-- ${GENERATED_MARKER}. Do not edit: the next export overwrites it.`,
          '     Edit the catalog under i18n/ instead. -->',
          '<resources>',
          ...body,
          '</resources>',
          '',
        ].join('\n'),
        generated: true,
        isOurs: (contents) => contents.includes(GENERATED_MARKER),
      })
    }

    return files
  },
}
