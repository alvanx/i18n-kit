/**
 * Deterministic file writing.
 *
 * The same catalog must produce the same bytes forever, on any machine, in any
 * Node version. Two things depend on it: CI can assert that committed generated
 * output matches a fresh export, and a translation run that touches one key
 * produces a one-key diff instead of a reformatted file.
 *
 * Keys are sorted by code point rather than left in insertion order. JavaScript
 * reorders integer-like object keys ("1" before "a") regardless of how they were
 * inserted, so relying on insertion order would be non-deterministic for exactly
 * the catalogs that use numeric-looking keys. The stringifier here never asks
 * the runtime for key order.
 */

import { writeFileSync, readFileSync, existsSync, mkdirSync, renameSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { randomBytes } from 'node:crypto'

/** Marker key placed in generated JSON so export can tell its own output from a hand-written file. */
export const GENERATED_KEY = '_generated'

export const GENERATED_NOTICE =
  'Generated by i18n-kit. Do not edit: your changes will be overwritten on the next export. Edit the catalog under i18n/ instead.'

const CODEPOINT = (a, b) => (a < b ? -1 : a > b ? 1 : 0)

/**
 * JSON with sorted keys, two-space indent, and a trailing newline.
 * Written by hand rather than via JSON.stringify's replacer so key order is
 * ours rather than the runtime's.
 */
export function canonicalJson(value, indent = 0) {
  const pad = '  '.repeat(indent)
  const padInner = '  '.repeat(indent + 1)

  if (value === null || value === undefined) return 'null'
  if (typeof value === 'string' || typeof value === 'number' || typeof value === 'boolean') {
    return JSON.stringify(value)
  }

  if (Array.isArray(value)) {
    if (value.length === 0) return '[]'
    const items = value.map((v) => `${padInner}${canonicalJson(v, indent + 1)}`)
    return `[\n${items.join(',\n')}\n${pad}]`
  }

  const keys = Object.keys(value)
    .filter((k) => value[k] !== undefined)
    .sort(CODEPOINT)
  if (keys.length === 0) return '{}'

  const entries = keys.map(
    (k) => `${padInner}${JSON.stringify(k)}: ${canonicalJson(value[k], indent + 1)}`,
  )
  return `{\n${entries.join(',\n')}\n${pad}}`
}

/** Serialize a document the way every catalog and generated JSON file is written. */
export function serializeJson(value) {
  return `${canonicalJson(value)}\n`
}

/**
 * Write only when the bytes differ, and replace atomically.
 *
 * Skipping an identical write keeps file modification times stable, which stops
 * a no-op export from invalidating a build cache. The atomic rename means an
 * interrupted run never leaves a half-written catalog behind.
 *
 * @returns {boolean} whether anything changed on disk
 */
export function writeIfChanged(path, contents) {
  if (existsSync(path) && readFileSync(path, 'utf8') === contents) return false

  mkdirSync(dirname(path), { recursive: true })
  const temp = join(dirname(path), `.${randomBytes(6).toString('hex')}.tmp`)
  writeFileSync(temp, contents, 'utf8')
  renameSync(temp, path)
  return true
}

/**
 * Refuse to overwrite a file the toolkit did not write.
 *
 * Export targets point at real platform paths, and a project may already have a
 * hand-written strings.xml or messages.json sitting there. Every generated file
 * carries an ownership marker in whatever form its format allows; a file at a
 * target path without one is somebody else's, and export stops rather than
 * eating it.
 *
 * @param {string} path
 * @param {(contents: string) => boolean} isOurs
 * @returns {{ok: true} | {ok: false, code: string, detail: string}}
 */
export function checkOwnership(path, isOurs) {
  if (!existsSync(path)) return { ok: true }

  let contents
  try {
    contents = readFileSync(path, 'utf8')
  } catch (err) {
    return { ok: false, code: 'GENERATED_UNOWNED', detail: `cannot read ${path}: ${err.message}` }
  }

  if (isOurs(contents)) return { ok: true }

  return {
    ok: false,
    code: 'GENERATED_UNOWNED',
    detail:
      `${path} exists and carries no i18n-kit marker, so it was not written by this tool. ` +
      `Move or delete it, or point this target somewhere else.`,
  }
}

/** Ownership test for generated JSON: the marker key is present at the top level. */
export const jsonIsOurs = (contents) => {
  try {
    return Object.hasOwn(JSON.parse(contents), GENERATED_KEY)
  } catch {
    return false
  }
}
