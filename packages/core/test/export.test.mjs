import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
import { loadProject } from '../src/catalog.mjs'
import { runExport, checkDrift, planExport } from '../src/export.mjs'
import { capabilityFindings, resolveLocaleTag, messagesForTarget } from '../src/adapters/index.mjs'
import { analyze } from '../src/icu.mjs'
import { sourceHash, contextHash, contentHash } from '../src/hash.mjs'
import { contractOf } from '../src/icu.mjs'
import { canonicalJson } from '../src/writer.mjs'
import { makeProject } from './helpers.mjs'

const SRC = 'Send {count, plural, one {# tab} other {# tabs}} to {device}?'
const DE = '{count, plural, one {# Tab} other {# Tabs}} an {device} senden?'

const src = (over = {}) => ({
  message: SRC,
  comment: 'Confirmation dialog title.',
  placeholders: { count: { type: 'number' }, device: { type: 'string' } },
  ...over,
})

const translated = (s, message) => ({
  message,
  origin: 'machine',
  review: 'none',
  sourceHash: sourceHash(s.message, contractOf(analyze(s.message))),
  contextHash: contextHash(s),
  contentHash: contentHash(message),
})

function project(spec) {
  const made = makeProject({
    config: { targets: { web: { adapter: 'web' } }, ...(spec.config ?? {}) },
    ...spec,
  })
  return { ...made, ...loadProject(made.config) }
}

const webFile = (root, name) => JSON.parse(readFileSync(join(root, 'build/i18n/web/locales', name), 'utf8'))

// --- the web adapter --------------------------------------------------------

test('emits one file per locale plus the source locale', () => {
  const s = src()
  const p = project({
    source: { app: { 'transfer.confirm': s } },
    translations: { de: { app: { 'transfer.confirm': translated(s, DE) } } },
  })
  const result = runExport(p.project)

  assert.deepEqual(result.findings, [])
  assert.equal(webFile(p.root, 'en.json').messages['transfer.confirm'], SRC)
  assert.equal(webFile(p.root, 'de.json').messages['transfer.confirm'], DE)
})

test('a missing translation is omitted, never filled with source text', () => {
  const p = project({ source: { app: { 'transfer.confirm': src() } } })
  runExport(p.project)

  const de = webFile(p.root, 'de.json')
  assert.equal(Object.hasOwn(de.messages, 'transfer.confirm'), false)
  // The failure this prevents: a complete-looking de.json full of English.
  assert.notEqual(JSON.stringify(de.messages), JSON.stringify(webFile(p.root, 'en.json').messages))
})

test('generated files carry an ownership marker', () => {
  const p = project({ source: { app: { 'a.b': src() } } })
  runExport(p.project)
  assert.match(webFile(p.root, 'en.json')._generated, /Generated by i18n-kit/)
})

test('export is deterministic: two runs produce identical bytes', () => {
  const s = src()
  const p = project({
    source: { app: { 'b.two': s, 'a.one': s, 'c.three': s } },
    translations: { de: { app: { 'a.one': translated(s, DE) } } },
  })

  const first = planExport(p.project).plans[0].files.map((f) => f.contents)
  const second = planExport(p.project).plans[0].files.map((f) => f.contents)
  assert.deepEqual(first, second)

  runExport(p.project)
  const written = runExport(p.project)
  assert.deepEqual(written.written, [], 'a second export should change nothing')
})

test('keys are sorted regardless of authoring order', () => {
  const s = src()
  const p = project({ source: { app: { 'z.last': s, 'a.first': s, 'm.middle': s } } })
  runExport(p.project)
  assert.deepEqual(Object.keys(webFile(p.root, 'en.json').messages), ['a.first', 'm.middle', 'z.last'])
})

test('canonical JSON does not depend on runtime key ordering', () => {
  const a = canonicalJson({ '2': 'b', '1': 'a', z: 'z', a: 'a' })
  const b = canonicalJson({ a: 'a', z: 'z', '1': 'a', '2': 'b' })
  assert.equal(a, b)
  assert.match(a, /^\{\n  "1"/)
})

// --- the generated type declaration -----------------------------------------

test('generates typed arguments, not just typed keys', () => {
  const p = project({
    source: {
      app: {
        'transfer.confirm': src(),
        'app.ok': { message: 'OK', comment: 'Button.' },
        'app.when': {
          message: 'at {when, date, short}',
          comment: 'Timestamp.',
          placeholders: { when: { type: 'date' } },
        },
      },
    },
  })
  runExport(p.project)
  const dts = readFileSync(join(p.root, 'build/i18n/web/keys.d.ts'), 'utf8')

  assert.match(dts, /"transfer\.confirm": \{ "count": number; "device": string \| number \}/)
  assert.match(dts, /"app\.ok": Record<string, never>/)
  assert.match(dts, /"app\.when": \{ "when": Date \| number \}/)
  assert.match(dts, /\/\*\* Confirmation dialog title\. \*\//)
})

test('a rich-text tag becomes a render hook in the types', () => {
  const p = project({
    source: {
      app: {
        'a.terms': {
          message: 'Read the <link>terms</link>',
          comment: 'Body.',
          placeholders: { link: { type: 'tag' } },
        },
      },
    },
  })
  runExport(p.project)
  const dts = readFileSync(join(p.root, 'build/i18n/web/keys.d.ts'), 'utf8')
  assert.match(dts, /"link": \(children: string\) => unknown/)
})

// --- ownership --------------------------------------------------------------

test('export refuses to overwrite a file it did not write', () => {
  const p = project({ source: { app: { 'a.b': src() } } })
  const target = join(p.root, 'build/i18n/web/locales')
  mkdirSync(target, { recursive: true })
  writeFileSync(join(target, 'en.json'), '{"messages":{"hand":"written"}}', 'utf8')

  const result = runExport(p.project)
  assert.ok(result.findings.some((f) => f.code === 'GENERATED_UNOWNED'))
  assert.equal(JSON.parse(readFileSync(join(target, 'en.json'), 'utf8')).messages.hand, 'written')
})

// --- drift ------------------------------------------------------------------

test('drift is detected when generated output is missing', () => {
  const p = project({ source: { app: { 'a.b': src() } } })
  assert.ok(checkDrift(p.project).some((f) => f.code === 'GENERATED_DRIFT' && /is missing/.test(f.detail)))
})

test('drift is detected when generated output is stale', () => {
  const p = project({ source: { app: { 'a.b': src() } } })
  runExport(p.project)
  writeFileSync(
    join(p.root, 'build/i18n/web/locales/en.json'),
    '{"_generated":"Generated by i18n-kit","locale":"en","messages":{}}\n',
    'utf8',
  )
  assert.ok(checkDrift(p.project).some((f) => /does not match a fresh export/.test(f.detail)))
})

test('no drift right after an export', () => {
  const p = project({ source: { app: { 'a.b': src() } } })
  runExport(p.project)
  assert.deepEqual(checkDrift(p.project), [])
})

// --- message selection ------------------------------------------------------

test('a message can opt out of a target', () => {
  const p = project({
    source: {
      app: {
        'a.everywhere': src(),
        'a.webonly': { ...src(), targets: ['web'] },
        'a.androidonly': { ...src(), targets: ['android'] },
      },
    },
  })
  const keys = messagesForTarget(p.project, 'web').map((m) => m.key)
  assert.deepEqual(keys, ['a.everywhere', 'a.webonly'])
})

test('deprecated keys are dropped from every target', () => {
  const p = project({
    source: {
      app: {
        'a.live': src(),
        'a.old': { ...src(), deprecated: { since: '2026-01-01' } },
      },
    },
  })
  assert.deepEqual(messagesForTarget(p.project, 'web').map((m) => m.key), ['a.live'])
})

// --- capabilities -----------------------------------------------------------

const limited = {
  id: 'limited',
  capabilities: {
    plurals: 'none',
    exactMatch: false,
    select: false,
    selectordinal: false,
    offset: false,
    nesting: 1,
    placeholders: 'positional',
    repeatedPlaceholders: false,
    numberDateSkeletons: false,
    richText: false,
    comments: 'none',
    needsLocaleMap: true,
  },
}

const capCodes = (message) =>
  capabilityFindings(analyze(message), limited, { targetName: 't' }).map((f) => f.detail)

test('every unsupported construct is named, not silently dropped', () => {
  assert.match(capCodes('{n, plural, one {# a} other {# b}}')[0], /cannot express a plural/)
  assert.match(capCodes('{n, selectordinal, one {#st} other {#th}}')[0], /selectordinal/)
  assert.match(capCodes('{g, select, other {x}}')[0], /select/)
  assert.match(capCodes('<b>bold</b>')[0], /rich-text tags/)
  assert.match(capCodes('{d, date, short}')[0], /number or date argument/)
  assert.match(capCodes('{a} and {a}')[0], /repeated placeholder/)
})

test('an unsupported construct carries advice, not just a refusal', () => {
  assert.match(capCodes('{g, select, other {x}}')[0], /separate keys chosen at the call site/)
})

test('the web adapter can express everything the catalog can', () => {
  const rich = '{n, plural, offset:1 =0 {none} one {# <b>tab</b>} other {# tabs at {when, date, short}}}'
  const p = project({ source: { app: { 'a.b': src({ message: 'x' }) } } })
  const { plans, findings } = planExport(p.project)
  assert.deepEqual(findings, [])
  assert.equal(plans.length, 1)
  // and the rich message itself trips nothing on the web adapter
  const web = plans[0]
  assert.ok(web.files.length > 0)
  assert.deepEqual(capabilityFindings(analyze(rich), { id: 'web', capabilities: { plurals: 'icu', exactMatch: true, select: true, selectordinal: true, offset: true, nesting: 3, placeholders: 'named', repeatedPlaceholders: true, numberDateSkeletons: true, richText: true, comments: 'none', needsLocaleMap: false } }, { targetName: 'web' }), [])
})

test('a target that needs a locale map errors rather than guessing', () => {
  const result = resolveLocaleTag('zh-Hans', { name: 't', localeMap: {} }, limited)
  assert.equal(result.ok, false)
  assert.equal(result.code, 'UNMAPPED_LOCALE')
  assert.match(result.detail, /zh-Hans/)
})

test('an explicit mapping is used as given', () => {
  const result = resolveLocaleTag('zh-Hans', { name: 't', localeMap: { 'zh-Hans': 'zh_CN' } }, limited)
  assert.deepEqual(result, { ok: true, tag: 'zh_CN' })
})

test('the web adapter passes BCP 47 through untouched', () => {
  const result = resolveLocaleTag('pt-BR', { name: 'web', localeMap: {} }, { capabilities: { needsLocaleMap: false }, localeTag: (l) => l })
  assert.deepEqual(result, { ok: true, tag: 'pt-BR' })
})
